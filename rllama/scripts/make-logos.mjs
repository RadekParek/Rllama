// Turns the vendor SVGs into a typed map the UI can inline.
//
// Source: @lobehub/icons-static-svg (MIT), which carries the official brand
// marks. We only inline the handful of vendors Rllama can talk to, so the
// bundle stays small (a few KB per logo).
//
// Usage: node scripts/make-logos.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const icons = join(root, 'node_modules', '@lobehub', 'icons-static-svg', 'icons');

/** key in the generated map -> svg file in the icon pack */
const WANTED = {
  anthropic: 'claude-color.svg',
  openai: 'openai.svg',
  deepseek: 'deepseek-color.svg',
  kimi: 'kimi-color.svg',
  gemini: 'gemini-color.svg',
  gemma: 'gemma-color.svg',
  qwen: 'qwen-color.svg',
  meta: 'meta-color.svg',
  mistral: 'mistral-color.svg',
  groq: 'groq.svg',
  glm: 'zhipu-color.svg',
  microsoft: 'microsoft-color.svg',
  nvidia: 'nvidia-color.svg',
  minimax: 'minimax-color.svg',
  xai: 'grok.svg',
  ollama: 'ollama.svg',
};

function clean(svg) {
  return svg
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s(width|height|style)="[^"]*"/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
    // The root element is replaced by the React wrapper, keep the children only.
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>$/, '');
}

const entries = [];
const missing = [];
for (const [key, file] of Object.entries(WANTED)) {
  try {
    const raw = readFileSync(join(icons, file), 'utf8');
    entries.push([key, clean(raw)]);
  } catch {
    missing.push(file);
  }
}

// viewBox for each key, read from the source file.
const viewBoxes = {};
for (const [key, file] of Object.entries(WANTED)) {
  try {
    const raw = readFileSync(join(icons, file), 'utf8');
    const match = /viewBox="([^"]+)"/.exec(raw);
    viewBoxes[key] = match ? match[1] : '0 0 24 24';
  } catch {
    viewBoxes[key] = '0 0 24 24';
  }
}

const out = `// Generated by scripts/make-logos.mjs — do not edit by hand.
// Brand marks: @lobehub/icons-static-svg (MIT).
export const LOGO_PATHS: Record<string, string> = {
${entries.map(([key, body]) => `  ${key}: ${JSON.stringify(body)},`).join('\n')}
};

export const LOGO_VIEWBOX: Record<string, string> = {
${Object.entries(viewBoxes)
  .filter(([key]) => entries.some(([entryKey]) => entryKey === key))
  .map(([key, box]) => `  ${key}: ${JSON.stringify(box)},`)
  .join('\n')}
};
`;

mkdirSync(join(root, 'src', 'ui'), { recursive: true });
writeFileSync(join(root, 'src', 'ui', 'logos.generated.ts'), out, 'utf8');
console.log(`wrote src/ui/logos.generated.ts with ${entries.length} logos`);
if (missing.length > 0) {
  console.warn('missing:', missing.join(', '));
}
